-- 按用户 + 推送状态查询（用户维度统计/重推）
create index if not exists idx_push_records_user_status
    on nightscout_push_records (gateway_user_id, push_status);

-- 按被监控对象 + 推送状态查询
create index if not exists idx_push_records_subject_status
    on nightscout_push_records (monitored_subject_id, push_status);

-- 重试调度器：按状态 + 下次重试时间捞取待重试记录
create index if not exists idx_push_records_pending_retry
    on nightscout_push_records (push_status, next_retry_at)
    where push_status in ('PENDING', 'FAILED');

-- 按目标查询推送记录
create index if not exists idx_push_records_target_id
    on nightscout_push_records (nightscout_target_id);
