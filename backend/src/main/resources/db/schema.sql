-- ============================================================
-- Hedwig 数据库建表脚本 (PostgreSQL)
-- ============================================================
-- 适配 Spring Boot 3 + JPA 后端，覆盖以下业务模块：
--   1. 用户信息
--   2. 设备厂商连接及用户关系
--   3. 被监控对象（CGM 佩戴者）
--   4. 血糖读数（来源设备信息）
--   5. Nightscout 远端配置（支持多个）
--   6. Nightscout 推送记录
--
-- 变更记录：
--   2025-03-20  v2  补齐 created_at/updated_at；修复 Entity-SQL 不一致；
--                    增加 gateway_users.nickname/status；优化索引；
--                    限制推送记录大字段长度。
-- ============================================================

-- ----------------------------------------------------------
-- 1. 用户信息
-- ----------------------------------------------------------
create table if not exists gateway_users (
    id              bigint generated by default as identity primary key,
    username        varchar(100)                not null,           -- 登录用户名，系统内唯一
    password_hash   varchar(255)                not null,           -- 密码哈希值（BCrypt），不保存明文
    nickname        varchar(100),                                   -- 用户昵称 / 显示名，前端展示用
    status          varchar(20)                 not null default 'ACTIVE', -- 账号状态：ACTIVE / DISABLED
    created_at      timestamp with time zone    not null default current_timestamp,
    updated_at      timestamp with time zone    not null default current_timestamp,

    constraint uk_gateway_users_username unique (username)
);

comment on table  gateway_users                    is '网关系统用户表';
comment on column gateway_users.id                 is '主键ID';
comment on column gateway_users.username           is '登录用户名，系统内唯一';
comment on column gateway_users.password_hash      is '密码哈希值，不保存明文密码';
comment on column gateway_users.nickname           is '用户昵称 / 显示名';
comment on column gateway_users.status             is '账号状态：ACTIVE-启用，DISABLED-禁用';
comment on column gateway_users.created_at         is '创建时间';
comment on column gateway_users.updated_at         is '最近修改时间';


-- ----------------------------------------------------------
-- 2. 设备厂商连接及用户关系
-- ----------------------------------------------------------
create table if not exists vendor_connections (
    id                bigint generated by default as identity primary key,
    gateway_user_id   bigint                      not null,         -- 关联 gateway_users.id
    vendor_type       varchar(32)                 not null,         -- 设备厂商类型：OTTAI / SISENSING / MICROTECH
    access_token      varchar(2048)               not null,         -- 厂商接口访问令牌
    vendor_user_id    varchar(128),                                 -- 用户在厂商平台中的用户ID
    token_expires_at  timestamp with time zone,                     -- 访问令牌过期时间
    token_status      varchar(32)                 not null default 'ACTIVE', -- 令牌状态：ACTIVE / EXPIRING_SOON / EXPIRED
    last_synced_at    timestamp with time zone,                     -- 最近一次从厂商同步数据的时间
    polling_interval_seconds integer,                               -- 连接级轮询间隔（秒），为空用厂商默认值
    created_at        timestamp with time zone    not null default current_timestamp,
    updated_at        timestamp with time zone    not null default current_timestamp,

    constraint fk_vendor_connections_gateway_user
        foreign key (gateway_user_id) references gateway_users (id)
        on delete cascade,
    constraint uk_vendor_connections_user_vendor
        unique (gateway_user_id, vendor_type)
);

-- 已有数据库的增量迁移必须位于列注释前，否则首次启动会因字段尚不存在而失败。
alter table vendor_connections
    add column if not exists polling_interval_seconds integer;

